import { one } from '../../core/rows.js';
import { field, invalid, type ResourceSpec } from '../../core/resource.js';
import { boqCreateBody, boqPatchBody, boqProjectFilter, boqStatusFilter, boqWbsFilter } from './schema.js';

export const BOQ_TABLE = 'core_boq_item';

/**
 * Bill of Quantities items (migration 0035). Errors use the BOQ_ITEM prefix: a second item code in one project is
 * 409 BOQ_ITEM_DUPLICATE, and an unknown project, unit or WBS node is 400 BOQ_ITEM_REFERENCE_NOT_FOUND. A WBS node
 * of another project is refused with 400 VALIDATION_ERROR on wbsNodeId. The amount is read-only.
 */
export const boqItemSpec: ResourceSpec = {
  table: BOQ_TABLE,
  prefix: 'BOQ_ITEM',
  label: 'BOQ item',
  fields: [
    field('projectId', 'uuid'),
    field('itemCode', 'citext'),
    field('description', 'text'),
    field('wbsNodeId', 'uuid'),
    field('uomId', 'uuid'),
    field('quantity', 'num'),
    field('rate', 'num'),
    // Generated by the database (quantity x rate). Neither input schema has it, so it is never written.
    field('amount', 'num'),
    field('status', 'text'),
  ],
  create: boqCreateBody,
  patch: boqPatchBody,
  filters: {
    projectId: { column: 'project_id', schema: boqProjectFilter },
    wbsNodeId: { column: 'wbs_node_id', schema: boqWbsFilter },
    status: { column: 'status', schema: boqStatusFilter },
  },
  orderBy: 'item_code, id',
  async prepare({ client, row }) {
    const wbsNodeId = row['wbsNodeId'];
    if (typeof wbsNodeId !== 'string') return {};
    const node = await one<{ project_id: string | null }>(
      client,
      'SELECT project_id FROM core_wbs_node WHERE id = $1',
      [wbsNodeId],
    );
    // An unknown node is left to the foreign key (400 BOQ_ITEM_REFERENCE_NOT_FOUND).
    if (node && node.project_id !== row['projectId']) {
      throw invalid({ path: 'wbsNodeId', message: 'The WBS node belongs to another project' });
    }
    return {};
  },
};
