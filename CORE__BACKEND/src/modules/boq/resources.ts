import { field, type ResourceSpec } from '../../core/resource.js';
import { boqCreateBody, boqPatchBody, boqProjectFilter, boqStatusFilter } from './schema.js';

export const BOQ_TABLE = 'core_boq_item';

/**
 * Bill of Quantities items (migration 0035). Errors use the BOQ_ITEM prefix: a second item code in one project is
 * 409 BOQ_ITEM_DUPLICATE, and an unknown project or unit is 400 BOQ_ITEM_REFERENCE_NOT_FOUND. The amount is read-only.
 */
export const boqItemSpec: ResourceSpec = {
  table: BOQ_TABLE,
  prefix: 'BOQ_ITEM',
  label: 'BOQ item',
  fields: [
    field('projectId', 'uuid'),
    field('itemCode', 'citext'),
    field('description', 'text'),
    field('uomId', 'uuid'),
    field('quantity', 'num'),
    field('rate', 'num'),
    // Generated by the database (quantity x rate). Neither input schema has it, so it is never written.
    field('amount', 'num'),
    field('status', 'text'),
  ],
  create: boqCreateBody,
  patch: boqPatchBody,
  filters: {
    projectId: { column: 'project_id', schema: boqProjectFilter },
    status: { column: 'status', schema: boqStatusFilter },
  },
  orderBy: 'item_code, id',
};
