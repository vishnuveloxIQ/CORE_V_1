import type { Pool } from 'pg';
import { tenantSchemaName } from './migrate.js';

/**
 * Generates TypeScript row types from the live schema (CORE-17-05), with no ORM: every table of one tenant schema
 * (all tenants share the same shape) and the shared schema becomes an interface whose fields are the columns as
 * node-postgres returns them. `npm run db:types` writes src/db/types.generated.ts; a test regenerates it from a fresh
 * migrated database and fails if the committed file is out of date.
 */

interface ColumnInfo {
  table_schema: string;
  table_name: string;
  column_name: string;
  udt_name: string;
  is_nullable: 'YES' | 'NO';
}

/** The TypeScript type node-postgres gives a column of this type, with its default parsers. */
function tsType(udt: string): string {
  const array = udt.startsWith('_');
  const base = array ? udt.slice(1) : udt;
  const scalar = (() => {
    switch (base) {
      case 'int2':
      case 'int4':
      case 'float4':
      case 'float8':
      case 'oid':
        return 'number';
      case 'int8':
      case 'numeric':
        return 'string'; // returned as text, so no precision is lost
      case 'bool':
        return 'boolean';
      case 'timestamptz':
      case 'timestamp':
      case 'date':
        return 'Date';
      case 'json':
      case 'jsonb':
        return 'unknown';
      case 'bytea':
        return 'Buffer';
      default:
        return 'string'; // uuid, text, citext, varchar, inet, time and anything else read as text
    }
  })();
  return array ? `${scalar}[]` : scalar;
}

const pascal = (name: string) =>
  name
    .split('_')
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');

/** The generated module's text. Deterministic: tables and columns are sorted by name. */
export async function generateDbTypes(pool: Pool, tenantId = 'acme'): Promise<string> {
  const tenantSchema = tenantSchemaName(tenantId);
  const { rows } = await pool.query<ColumnInfo>(
    `SELECT c.table_schema, c.table_name, c.column_name, c.udt_name, c.is_nullable
     FROM information_schema.columns c
     JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
     WHERE c.table_schema IN ($1, 'shared') AND t.table_type = 'BASE TABLE' AND c.table_name <> 'core_migration'
     ORDER BY c.table_schema, c.table_name, c.column_name`,
    [tenantSchema],
  );
  const tables = new Map<string, ColumnInfo[]>();
  for (const row of rows) {
    const key = `${row.table_schema === 'shared' ? 'shared' : 'tenant'}.${row.table_name}`;
    tables.set(key, [...(tables.get(key) ?? []), row]);
  }
  const out: string[] = [
    '// Generated by `npm run db:types` from the migrated schema. Do not edit by hand.',
    '// Tenant tables are the same in every tenant_<id> schema. Shared tables live in the shared schema.',
    '',
  ];
  for (const [key, columns] of [...tables].sort(([a], [b]) => a.localeCompare(b))) {
    const [scope, table] = key.split('.') as [string, string];
    out.push(`/** ${scope === 'shared' ? 'shared' : 'tenant_<id>'}.${table} */`);
    out.push(`export interface ${pascal(scope === 'shared' ? `shared_${table}` : table)}Row {`);
    for (const column of columns) {
      out.push(`  ${column.column_name}: ${tsType(column.udt_name)}${column.is_nullable === 'YES' ? ' | null' : ''};`);
    }
    out.push('}', '');
  }
  return out.join('\n');
}
